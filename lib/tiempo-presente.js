// "02", "2" or " 02 " → its meaning, or "" for anything that isn't a code of the table.
export function describirTiempoPresente(codigo) {
  const t = String(codigo ?? "").trim();
  if (!/^\d{1,2}$/.test(t)) return "";
  return TIEMPO_PRESENTE[t.padStart(2, "0")] || "";
}
